"""Build generic, non-prescriptive recommendations.

Specific treatment advice requires expert validation and is intentionally not
generated by the foundation code. The farmer is directed to verify data and
consult a qualified local expert when a configured range is exceeded.
"""

from app.schemas.risk import RecommendationItem, RiskFactor


def build_recommendations(factors: list[RiskFactor]) -> list[RecommendationItem]:
    configured = [factor for factor in factors if factor.status != "not_configured"]

    if not configured:
        return []

    out_of_range = [
        factor
        for factor in configured
        if factor.status in ("below_range", "above_range")
    ]

    if not out_of_range:
        return [
            RecommendationItem(
                title="Continue routine monitoring",
                description_bn=(
                    "পানির মান নির্ধারিত সীমার মধ্যে আছে। নিয়মিত পরীক্ষা চালিয়ে যান।"
                ),
                priority="low",
                category="monitoring",
            )
        ]

    return [
        RecommendationItem(
            title="Verify the reading and consult an expert",
            description_bn=(
                "একটি বা একাধিক পানির প্যারামিটার নির্ধারিত সীমার বাইরে আছে। "
                "সেন্সর ও ম্যানুয়াল টেস্ট আবার যাচাই করুন এবং স্থানীয় "
                "অ্যাকুয়াকালচার বিশেষজ্ঞের পরামর্শ নিন।"
            ),
            priority="high",
            category="expert_consultation",
        ),
        RecommendationItem(
            title="Check sensor calibration",
            description_bn=(
                "পরিমাপের নির্ভরযোগ্যতা নিশ্চিত করতে সংশ্লিষ্ট সেন্সরের "
                "ক্যালিব্রেশন অবস্থা যাচাই করুন।"
            ),
            priority="medium",
            category="calibration",
        ),
    ]
